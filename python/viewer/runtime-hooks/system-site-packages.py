import sys
import os

python_dir = f"/usr/lib/python{sys.version_info.major}.{sys.version_info.minor}"
for candidate in [
    f"{python_dir}/site-packages",
    f"{python_dir}/dist-packages",
    python_dir,
]:
    if os.path.isdir(candidate) and candidate not in sys.path:
        sys.path.append(candidate)
